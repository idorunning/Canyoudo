// Post-build step. Reads each article's `redirectFrom` frontmatter and writes
// a Netlify `_redirects` file so that when an article moves between sections
// (its `section` field changes, and with it its URL), the old paths 301 to the
// new one. Runs automatically after `astro build` via the npm "postbuild" hook.
//
// It also keeps the retired `/og/…​.png` share-card paths alive (see below).
import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';

const CONTENT_DIR = 'src/content/articles';
const OUT = 'dist/_redirects';

function frontmatter(text) {
  if (!text.startsWith('---')) return '';
  const end = text.indexOf('\n---', 3);
  return end === -1 ? '' : text.slice(3, end);
}

function getScalar(fm, key) {
  const m = fm.match(new RegExp(`^${key}:\\s*(.+)$`, 'm'));
  return m ? m[1].trim().replace(/^["']|["']$/g, '') : null;
}

function getList(fm, key) {
  // Inline form: key: ["/a", "/b"]
  const inline = fm.match(new RegExp(`^${key}:\\s*\\[(.*)\\]\\s*$`, 'm'));
  if (inline) {
    return inline[1]
      .split(',')
      .map(s => s.trim().replace(/^["']|["']$/g, ''))
      .filter(Boolean);
  }
  // Block form:
  //   key:
  //     - /a
  //     - /b
  const lines = fm.split('\n');
  const start = lines.findIndex(l => new RegExp(`^${key}:\\s*$`).test(l));
  if (start === -1) return [];
  const out = [];
  for (let i = start + 1; i < lines.length; i++) {
    const m = lines[i].match(/^\s*-\s*(.+)$/);
    if (!m) break;
    out.push(m[1].trim().replace(/^["']|["']$/g, ''));
  }
  return out;
}

const rules = [];
if (existsSync(CONTENT_DIR)) {
  for (const file of readdirSync(CONTENT_DIR)) {
    if (!/\.(md|mdx)$/.test(file)) continue;
    const text = readFileSync(join(CONTENT_DIR, file), 'utf8');
    const fm = frontmatter(text);
    if (getScalar(fm, 'draft') === 'true') continue;
    const section = getScalar(fm, 'section') || 'police-policy';
    const slug = file.replace(/\.(md|mdx)$/, '');
    const target = `/${section}/${slug}/`;
    for (const from of getList(fm, 'redirectFrom')) {
      const f = from.startsWith('/') ? from : `/${from}`;
      if (f.replace(/\/$/, '') === target.replace(/\/$/, '')) continue; // no self-redirect
      rules.push(`${f}  ${target}  301`);
    }

    // Share cards were PNG until the card became a photograph and moved to JPEG.
    // X, Facebook and LinkedIn cache a card against the image URL they scraped,
    // so a cached entry still asks for the .png — and a 404 there shows as no
    // preview at all, not as the old card. Point it at the JPEG until those
    // caches turn over. Safe to drop once they have.
    rules.push(`/og/${section}/${slug}.png  /og/${section}/${slug}.jpg  301`);
  }
}

if (!existsSync('dist')) mkdirSync('dist', { recursive: true });
const header = '# Generated by scripts/generate-redirects.mjs — do not edit by hand.\n';
writeFileSync(OUT, rules.length ? header + rules.join('\n') + '\n' : header);
console.log(`generate-redirects: wrote ${rules.length} redirect rule(s) to ${OUT}`);
